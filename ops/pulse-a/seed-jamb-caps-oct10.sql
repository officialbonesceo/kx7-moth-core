<h2>Why CAPS timing matters for your wallet</h2>
<p>When CAPS is slow or offline, schools cannot finish offers cleanly. When it is back, institutions are pushed to <em>speed up</em>. That means offers can arrive in a cluster. If you are not checking CAPS and your registered email/phone, you can miss the short window to accept — and then spend more on transport, cybercafé runs, or “agents” who claim they can fix what is simply a deadline problem.</p>
<p>Recent reporting around late September 2026 described CAPS being restored after a multi-day disruption, with public universities still expected to conclude admissions around <strong>31 October 2026</strong>, private universities later in November, and other tertiary types by end of December. Those dates come from policy-meeting style reporting — treat them as <strong>checkpoints to verify</strong>, not as LaneCash promises.</p>

<h2>What to do this week (no agent required)</h2>
<ol>
<li>Open CAPS with your own profile. Screenshot any offer screen.</li>
<li>Accept or reject only after you confirm the course and campus on the school’s official site.</li>
<li>Upload or refresh O’Level data if you were awaiting NECO/WAEC results — incomplete credentials slow offers.</li>
<li>Ignore anyone who asks you to pay into a personal account to “force CAPS approval”.</li>
</ol>

<h2>The one-time O’Level verification fee idea</h2>
<p>News coverage has described JAMB and WAEC moving toward a <strong>single remote verification fee</strong> (reported around ₦4,000 in some September 2026 write-ups) so candidates are not charged repeatedly by every school for the same result check. Details can change. Before you pay:</p>
<ul>
<li>Use only links published by JAMB or WAEC — not a forwarded WhatsApp PDF.</li>
<li>Keep the receipt and reference number in a folder with your JAMB registration slip.</li>
<li>If a school still demands a separate “verification” into a personal account, stop and ask the school’s official admissions email.</li>
</ul>

<h2>Budget line for admission season</h2>
<p>Treat admission season like a small project budget:</p>
<ul>
<li><strong>Fixed:</strong> JAMB-related official fees you can see on the portal, result verification if required, passport photos.</li>
<li><strong>Flexible:</strong> data, printing, one trip to a trusted CBT/café if your phone is unreliable.</li>
<li><strong>Zero line:</strong> “activation”, “slot”, “upgrade to merit list”, or POS deposits to strangers.</li>
</ul>
<p>If cash is tight, prioritise official portal steps over buying more “sure cut-off” PDFs online. Cut-off talk without the school’s own circular is noise.</p>

<h2>Scam patterns that spike when CAPS is busy</h2>
<ul>
<li>Fake CAPS screenshots asking you to “clear” a balance.</li>
